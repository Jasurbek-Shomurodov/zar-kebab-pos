#!/usr/bin/env node
// Writes the migration manifest the Settings health button compares with the live database.
// Runs before every build; tests/migrationManifest.test.js fails when the committed copy is stale.
import { writeFileSync } from 'node:fs'
import { migrationFiles, recentFunctionFingerprints } from './migrationTools.js'

export const manifestPath = new URL('../src/generated/migrationManifest.js', import.meta.url)

export function buildMigrationManifestSource(files = migrationFiles()) {
  const manifest = {
    files: files.map(({ filename, sha256 }) => ({ filename, sha256 })),
    functions: recentFunctionFingerprints(files),
  }
  return '// Generated by scripts/build-migration-manifest.js. Do not edit.\n'
    + `export default ${JSON.stringify(manifest, null, 1)}\n`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(manifestPath, buildMigrationManifestSource())
  console.log('Wrote src/generated/migrationManifest.js')
}
